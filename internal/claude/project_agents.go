package claude

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"github.com/kingpinXD/factory/internal/agents"
	"github.com/kingpinXD/factory/internal/store"
	"go.yaml.in/yaml/v3"
)

const projectAgentHeader = "---\n# Generated by Factory. Do not edit.\n"

func writeProjectAgents(dir, definitions string) error {
	defs := map[string]agents.Agent{}
	if definitions != "" {
		if err := json.Unmarshal([]byte(definitions), &defs); err != nil {
			return fmt.Errorf("project agents: %w", err)
		}
	}
	files := map[string][]byte{}
	for name, agent := range defs {
		if err := store.CheckID(name); err != nil {
			return fmt.Errorf("project agent %q: %w", name, err)
		}
		frontmatter, err := yaml.Marshal(struct {
			Name        string   `yaml:"name"`
			Description string   `yaml:"description"`
			Model       string   `yaml:"model"`
			Effort      string   `yaml:"effort,omitempty"`
			Tools       []string `yaml:"tools,omitempty"`
		}{name, agent.Description, agent.Model, agent.Effort, agent.Tools})
		if err != nil {
			return err
		}
		files[name+".md"] = []byte(projectAgentHeader + string(frontmatter) + "---\n" + agent.Prompt)
	}
	for _, part := range []string{".claude", "agents"} {
		dir = filepath.Join(dir, part)
		if err := os.Mkdir(dir, 0700); err != nil && !os.IsExist(err) {
			return err
		}
		info, err := os.Lstat(dir)
		if err != nil {
			return err
		}
		if !info.IsDir() {
			return fmt.Errorf("project agents directory is not a directory: %s", dir)
		}
	}
	for name := range files {
		file := filepath.Join(dir, name)
		owned, err := factoryOwnsProjectAgent(file)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if !owned {
			return fmt.Errorf("project agent %s is not owned by Factory", file)
		}
	}
	for name, data := range files {
		if err := writeProjectAgent(filepath.Join(dir, name), data); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if filepath.Ext(entry.Name()) != ".md" || files[entry.Name()] != nil {
			continue
		}
		file := filepath.Join(dir, entry.Name())
		owned, err := factoryOwnsProjectAgent(file)
		if err != nil {
			return err
		}
		if owned {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	return nil
}

func factoryOwnsProjectAgent(file string) (bool, error) {
	info, err := os.Lstat(file)
	if err != nil {
		return false, err
	}
	if !info.Mode().IsRegular() {
		return false, nil
	}
	data, err := os.ReadFile(file)
	return bytes.HasPrefix(data, []byte(projectAgentHeader)), err
}

func writeProjectAgent(file string, data []byte) error {
	f, err := os.CreateTemp(filepath.Dir(file), ".factory-agent-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), file)
}
