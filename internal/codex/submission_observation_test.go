func retireSubmissionHost(t *testing.T, identity ProcessIdentity) {
	t.Helper()
	if err := syscall.Kill(identity.PID, syscall.SIGKILL); err != nil {
		t.Fatal(err)
	}
	deadline := time.Now().Add(2 * time.Second)
	for time.Now().Before(deadline) {
		if syscall.Kill(identity.PID, 0) == syscall.ESRCH && syscall.Kill(-identity.Group, 0) == syscall.ESRCH {
			return
		}
		time.Sleep(time.Millisecond)
	}
	t.Fatal("private input host did not exit")
}

type submissionHistoryCaller struct {
	t       *testing.T
	pages   []string
	methods []string
}

func (p *submissionHistoryCaller) Call(_ context.Context, method string, params any, out any) error {
	p.t.Helper()
	p.methods = append(p.methods, method)
	if method == "thread/read" {
		return json.Unmarshal([]byte(`{"thread":{"id":"thread"}}`), out)
	}
	if method != "thread/turns/list" {
		p.t.Fatalf("observation attempted non-history method %s", method)
	}
	values := params.(map[string]any)
	if values["threadId"] != "thread" || values["itemsView"] != "full" || values["sortDirection"] != "desc" {
		p.t.Fatalf("unsafe history request: %v", values)
	}
	if len(p.pages) == 0 {
		return errors.New("provider read unavailable")
	}
	data := p.pages[0]
	p.pages = p.pages[1:]
	return json.Unmarshal([]byte(data), out)
}

// The fixture follows JSON schema generated by pinned codex-cli 0.162.1.
// It is a protocol fixture, not a captured provider response.
func TestSubmissionObservationScopesStartAndSteerUsingPinnedProtocol(t *testing.T) {
	data, err := os.ReadFile("testdata/submission-turns-0.162.1.json")
	if err != nil {
		t.Fatal(err)
	}
	after := `{"data":[{"id":"ack-turn","status":"completed","items":[]}],"nextCursor":null}`
	oldInput := `{"data":[{"id":"ack-turn","status":"completed","items":[{"id":"old","type":"userMessage","content":[{"type":"text","text":"uncertain input"}]}]}],"nextCursor":null}`
	input := "uncertain input"
	for _, test := range []struct {
		name, method, anchor, target, outcome string
		pages                                 []string
		missingInput                          bool
	}{
		{name: "start pages after ack", method: "turn/start", anchor: "ack-turn", outcome: "arrived", pages: []string{string(data), after}},
		{name: "input only in acknowledged turn", method: "turn/start", anchor: "ack-turn", outcome: "not_arrived", pages: []string{oldInput}},
		{name: "missing acknowledged boundary", method: "turn/start", anchor: "not-recorded", outcome: "unknown", pages: []string{strings.Replace(string(data), `"nextCursor": "older-page"`, `"nextCursor": null`, 1)}},
		{name: "steer inside target", method: "turn/steer", target: "new-turn", outcome: "arrived", pages: []string{string(data)}},
		{name: "steer ignores other turns", method: "turn/steer", target: "ack-turn", outcome: "not_arrived", pages: []string{string(data), after}},
		{name: "missing target", method: "turn/steer", target: "absent", outcome: "unknown", pages: []string{after}},
		{name: "legacy input unavailable", method: "turn/start", outcome: "unknown", missingInput: true, pages: []string{after}},
		{name: "partial items", method: "turn/steer", target: "new-turn", outcome: "unknown", pages: []string{strings.Replace(string(data), `"itemsView": "full"`, `"itemsView": "summary"`, 1)}},
		{name: "missing turns array", method: "turn/start", outcome: "unknown", pages: []string{`{"nextCursor":null}`}},
		{name: "missing full items", method: "turn/steer", target: "new-turn", outcome: "unknown", pages: []string{`{"data":[{"id":"new-turn","status":"completed"}],"nextCursor":null}`}},
		{name: "pagination repeats cursor", method: "turn/start", anchor: "ack-turn", outcome: "unknown", pages: []string{`{"data":[],"nextCursor":"loop"}`, `{"data":[],"nextCursor":"loop"}`}},
	} {
		t.Run(test.name, func(t *testing.T) {
			p := &submissionHistoryCaller{t: t, pages: test.pages}
			query := SubmissionQuery{Method: test.method, TargetTurnID: test.target, AfterTurnID: test.anchor, InputSHA256: inputDigest(input), InputText: &input}
			if test.missingInput {
				query.InputText = nil
			}
			got := ReadSubmissionObservation(t.Context(), p, "thread", query)
			if got.Outcome != test.outcome {
				t.Fatalf("outcome %s want %s: %+v", got.Outcome, test.outcome, got)
			}
			if err := ValidateSubmissionObservation(got, "thread", query); err != nil {
				t.Fatal(err)
			}
			if test.name == "start pages after ack" && strings.Join(p.methods, ",") != "thread/read,thread/turns/list,thread/turns/list" {
				t.Fatalf("did not page across acknowledged boundary: %v", p.methods)
			}
		})
	}
}

func TestSubmissionObservationRequiresBothWritersGone(t *testing.T) {
	r, spec, _, _ := attemptWorld(t)
	ref := preparedAttempt(t, r, spec)
	record := claimedAttempt(t, r, ref)
	server, _ := ownSleep(t)
	record.Server = server
	retireSubmissionHost(t, record.Host)
	calls := 0
	r.SubmissionObserver = func(context.Context, Record) (Caller, func(), error) {
		calls++
		return &submissionHistoryCaller{t: t}, nil, nil
	}
	input := "uncertain input"
	query := SubmissionQuery{Method: "turn/start", InputSHA256: inputDigest(input), InputText: &input}
	if _, err := r.ObserveSubmission(t.Context(), record, query); !errors.Is(err, ErrObservationUnknown) {
		t.Fatalf("live server permitted history settlement: %v", err)
	}
	if calls != 0 {
		t.Fatal("opened observer while server was live")
	}
	retireSubmissionHost(t, server)
	record.Server.Birth = ""
	if _, err := r.ObserveSubmission(t.Context(), record, query); !errors.Is(err, ErrObservationUnknown) {
		t.Fatalf("missing process birth permitted settlement: %v", err)
	}
}

func TestSubmissionSettledFactsFollowOnlySelectedClosedAncestry(t *testing.T) {
	r, spec, _, _ := attemptWorld(t)
	ref := preparedAttempt(t, r, spec)
	record := claimedAttempt(t, r, ref)
	if err := r.beginSubmission(&record, "uncertain-key", "turn/start", "", "uncertain input"); err != nil {
		t.Fatal(err)
	}
	record.Server = record.Host
	if err := r.save(&record); err != nil {
		t.Fatal(err)
	}
	retireSubmissionHost(t, record.Host)
	calls := 0
	r.SubmissionObserver = func(context.Context, Record) (Caller, func(), error) {
		calls++
		return &submissionHistoryCaller{t: t, pages: []string{`{"data":[],"nextCursor":null}`}}, nil, nil
	}
	if err := r.CloseAttempt(t.Context(), ref, "unknown_submission"); err != nil {
		t.Fatal(err)
	}
	if err := r.CloseAttempt(t.Context(), ref, "unknown_submission"); err != nil {
		t.Fatal(err)
	}
	if calls != 1 {
		t.Fatalf("closed attempt re-observed %d times", calls)
	}
	successor, err := r.SelectSuccessor(t.Context(), ref, "successor", spec)
	if err != nil {
		t.Fatal(err)
	}
	facts, err := r.SettledSubmissions(t.Context(), spec.Name)
	if err != nil || len(facts) != 1 || facts[0].Key != "uncertain-key" || facts[0].InputText == nil || *facts[0].InputText != "uncertain input" || facts[0].Outcome != "not_arrived" {
		t.Fatalf("lost settled input across successor: %+v %v", facts, err)
	}
	again, err := r.SelectSuccessor(t.Context(), ref, "successor", spec)
	if err != nil || again != successor {
		t.Fatalf("successor duplicated: %v %v", again, err)
	}
	closed, err := r.readAttempt(ref)
	if err != nil {
		t.Fatal(err)
	}
	if got := closed.Closure.Submissions[0].Outcome; got != "not_arrived" {
		t.Fatalf("observation not durable: %s", got)
	}
	closed.Closure.Submissions[0].ObservedAt = closed.Closure.ClosedAt.Add(time.Second)
	if err := validateClosure(closed); !errors.Is(err, ErrAttemptConflict) {
		t.Fatalf("closure accepted observation after closure: %v", err)
	}
}

func TestSubmissionIntentPinsInputAndLastAcknowledgedTurn(t *testing.T) {
	r, spec, _, _ := attemptWorld(t)
	ref := preparedAttempt(t, r, spec)
	record := claimedAttempt(t, r, ref)
	if err := r.beginSubmission(&record, "first", "turn/start", "", "first input"); err != nil {
		t.Fatal(err)
	}
	if err := r.ackSubmission(&record, record.Submissions[0].ID, "last-acknowledged-turn"); err != nil {
		t.Fatal(err)
	}
	record.State = "idle"
	if err := r.save(&record); err != nil {
		t.Fatal(err)
	}
	if err := r.beginSubmission(&record, "lost", "turn/start", "", "uncertain input"); err != nil {
		t.Fatal(err)
	}
	sub := record.Submissions[1]
	if sub.InputText == nil || *sub.InputText != "uncertain input" || sub.AfterTurnID != "last-acknowledged-turn" {
		t.Fatalf("incomplete immutable submission scope: %+v", sub)
	}
	_, err := r.mutateAttempt(ref, record.Revision, "submission", func(next *Record) error {
		text := "changed input"
		next.Submissions[1].InputText = &text
		next.Submissions[1].InputSHA256 = inputDigest(text)
		return nil
	})
	if !errors.Is(err, ErrAttemptConflict) {
		t.Fatalf("uncertain input was mutable: %v", err)
	}
}

func TestSubmissionFactsRetainClosedOutcomeAndCurrentInputAcknowledgement(t *testing.T) {
	r, spec, _, _ := attemptWorld(t)
	previous := preparedAttempt(t, r, spec)
	record := claimedAttempt(t, r, previous)
	if err := r.beginSubmission(&record, "uncertain-key", "turn/start", "", "uncertain input"); err != nil {
		t.Fatal(err)
	}
	record.Server = record.Host
	if err := r.save(&record); err != nil {
		t.Fatal(err)
	}
	retireSubmissionHost(t, record.Host)
	r.SubmissionObserver = func(context.Context, Record) (Caller, func(), error) {
		return &submissionHistoryCaller{t: t, pages: []string{`{"data":[],"nextCursor":null}`}}, nil, nil
	}
	if err := r.CloseAttempt(t.Context(), previous, "unknown_submission"); err != nil {
		t.Fatal(err)
	}
	closedThread, closedInputs, err := r.CurrentSubmissionInputs(t.Context(), spec.Name)
	if err != nil || closedThread != "" || len(closedInputs) != 0 {
		t.Fatalf("closed source was reused as successor destination: %q %+v %v", closedThread, closedInputs, err)
	}
	next, err := r.SelectSuccessor(t.Context(), previous, "replacement", spec)
	if err != nil {
		t.Fatal(err)
	}
	facts, err := r.SettledSubmissions(t.Context(), spec.Name)
	if err != nil || len(facts) != 1 || facts[0].Key != "uncertain-key" || facts[0].Outcome != "not_arrived" || facts[0].ThreadID != "thread" || facts[0].InputText == nil || *facts[0].InputText != "uncertain input" || facts[0].ClosedAt.IsZero() {
		t.Fatalf("closed outcome lost: %+v %v", facts, err)
	}
	thread, inputs, err := r.CurrentSubmissionInputs(t.Context(), spec.Name)
	if err != nil || thread != "" || len(inputs) != 1 || inputs[0].State != "queued" || inputs[0].InputText == nil || *inputs[0].InputText != spec.Prompt {
		t.Fatalf("prepared initial input lost: %q %+v %v", thread, inputs, err)
	}
	current := claimedAttempt(t, r, next)
	initial, err := initialHostCommand(current)
	if err != nil {
		t.Fatal(err)
	}
	if err := r.beginSubmission(&current, initial.Key, "turn/start", "", initial.Text); err != nil {
		t.Fatal(err)
	}
	_, inputs, err = r.CurrentSubmissionInputs(t.Context(), spec.Name)
	if err != nil || len(inputs) != 1 || inputs[0].State != "intent" {
		t.Fatalf("pending initial input lost: %+v %v", inputs, err)
	}
	if err := r.ackSubmission(&current, current.Submissions[0].ID, "new-turn"); err != nil {
		t.Fatal(err)
	}
	thread, inputs, err = r.CurrentSubmissionInputs(t.Context(), spec.Name)
	if err != nil || thread != "thread" || len(inputs) != 1 || inputs[0].State != "acknowledged" {
		t.Fatalf("actual initial ACK lost: %q %+v %v", thread, inputs, err)
	}
}
