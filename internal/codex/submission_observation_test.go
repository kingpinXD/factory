func TestSubmissionObservationRetainsPersistedUserMessageContent(t *testing.T) {
	var item Item
	if err := json.Unmarshal([]byte(`{"id":"input","type":"userMessage","content":[{"type":"text","text":"uncertain input","text_elements":[]}]}`), &item); err != nil {
		t.Fatal(err)
	}
	data, err := json.Marshal(item)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), `"content":[`) || !strings.Contains(string(data), `uncertain input`) {
		t.Fatalf("persisted user input was discarded: %s", data)
	}
}

